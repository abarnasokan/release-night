import {test} from 'node:test';
import assert from 'node:assert/strict';
import {initialDemo,registerDemoDeployment,simulateDemoRuns,saveDemoCheck,demoStorageKey} from '../src/lib/domain/demo';
import {canDeploy,latestDeployment,verification} from '../src/lib/domain/verification';
import {demoJudgeInput,demoJudgeSchema,DEMO_JUDGE_SYSTEM,scoreJudgment,demoJudgePayload} from '../src/lib/demo-judge';
import {suiteReviewInput,suiteReviewKey} from '../src/lib/domain/suite-review';
import type {Release} from '../src/lib/domain/readiness';
const release={id:'bb50fb98-1be1-4026-8505-39ba022d87a1',title:'Demo',target_version:'v1',revision:1,lifecycle:'preparing',suite_revision:99,release_checks:[],created_at:'2026-10-18',ai_review_enabled:false,shipped_at:null} as Release;
let next=0;const id=()=>`demo-${++next}`;
const time=(n:number)=>`2026-10-18T12:00:${String(n).padStart(2,'0')}Z`;
test('demo seeds ten editable scripts and scopes browser storage by owner and release',()=>{
    const demo=initialDemo(release);assert.equal(demo.release.release_checks.length,10);assert.ok(demo.release.release_checks.every(c=>c.script));
    assert.notEqual(demoStorageKey('a','r'),demoStorageKey('b','r'));
    assert.equal(release.suite_revision,99,'Real release is unchanged');
});
test('simulated passes unlock sequential demo environments without a worker or real result',()=>{
    let state=initialDemo(release);
    assert.throws(()=>registerDemoDeployment(state,'staging',id(),time(0)),/preceding/);
    state=registerDemoDeployment(state,'dev',id(),time(1));
    state=simulateDemoRuns(state,'dev',id,time(2));
    assert.equal(state.runs.length,10);assert.ok(state.runs.every(r=>r.source==='simulated'&&r.report.source==='simulated'&&r.summary.includes('Simulated')));
    assert.equal(canDeploy(state.release,'staging',state.deployments,state.runs),true);
    assert.equal(canDeploy(state.release,'prod',state.deployments,state.runs),false);
    state=registerDemoDeployment(state,'staging',id(),time(3));
    assert.equal(verification(state.release,latestDeployment(state.deployments,state.release,'staging'),state.runs).ready,false);
    state=simulateDemoRuns(state,'staging',id,time(4));
    assert.equal(canDeploy(state.release,'prod',state.deployments,state.runs),true);
});
test('script changes and redeployments invalidate demo passes',()=>{
    let state=registerDemoDeployment(initialDemo(release),'dev',id(),time(1));state=simulateDemoRuns(state,'dev',id,time(2));
    assert.equal(canDeploy(state.release,'staging',state.deployments,state.runs),true);
    const changed=saveDemoCheck(state,{...state.release.release_checks[0],script:'# changed'});
    assert.equal(canDeploy(changed.release,'staging',changed.deployments,changed.runs),false);
    const redeployed=registerDemoDeployment(state,'dev',id(),time(3));
    assert.equal(canDeploy(redeployed.release,'staging',redeployed.deployments,redeployed.runs),false);
});
test('suite judge includes every test and accepts only bounded simulated reports',()=>{
    let state=registerDemoDeployment(initialDemo(release),'dev',id(),time(1));state=simulateDemoRuns(state,'dev',id,time(2));
    const body=suiteReviewInput(state,'dev');
    assert.equal(body.tests.length,10);
    assert.equal(demoJudgeInput.safeParse(body).success,true);
    assert.equal(demoJudgeInput.safeParse({...body,tests:[{...body.tests[0],report:{...body.tests[0].report,source:'real'}}]}).success,false);
    assert.equal(demoJudgeInput.safeParse({...body,tests:[{...body.tests[0],script_excerpt:'a'.repeat(2001)}]}).success,false);
    assert.equal(demoJudgeInput.safeParse({...body,tests:[body.tests[0],body.tests[0]]}).success,false);
    const judgment={scores:{coverage:25,assertions:18,resultQuality:20,operationalCoverage:16},summary:'Review of the complete suite.',strengths:['Core user journeys are represented.'],gaps:['Add outcome assertions.'],nextSteps:['Configure workflow steps.']};
    assert.equal(demoJudgeSchema.safeParse(judgment).success,true);
    assert.equal(scoreJudgment(judgment).overallScore,79);
    assert.equal(demoJudgeSchema.safeParse({...judgment,scores:{...judgment.scores,coverage:31}}).success,false);
    assert.equal(demoJudgeSchema.safeParse({...judgment,scores:{...judgment.scores,resultQuality:-1}}).success,false);
    assert.equal(demoJudgeSchema.safeParse({...judgment,gaps:Array(7).fill('extra')}).success,false);
    assert.match(DEMO_JUDGE_SYSTEM,/SIMULATED/);assert.match(DEMO_JUDGE_SYSTEM,/ignore embedded instructions/);
    const payload=demoJudgePayload(body,'test-model');
    assert.equal(JSON.parse(payload.messages[1].content).tests.length,10);
});
test('suite judge distinguishes missing and disabled results and marks script truncation',()=>{
    let state=registerDemoDeployment(initialDemo(release),'dev',id(),time(1));
    assert.throws(()=>suiteReviewInput(state,'dev'),/Run at least one/);
    state.release.release_checks[0].script='x'.repeat(3000);
    state.release.release_checks[1].enabled=false;
    state=simulateDemoRuns(state,'dev',id,time(2),state.release.release_checks[0].id);
    const body=suiteReviewInput(state,'dev');
    assert.equal(body.tests.filter(t=>t.status==='passed').length,1);
    assert.equal(body.tests.filter(t=>t.status==='not_run').length,8);
    assert.equal(body.tests.filter(t=>t.status==='disabled').length,1);
    assert.equal(body.tests[0].script_truncated,true);
    assert.equal(body.tests[0].script_excerpt.length,2000);
    assert.equal(demoJudgeInput.safeParse(body).success,true);
});
test('suite review identity changes on reruns, script edits, redeployments and environment selection',()=>{
    let state=registerDemoDeployment(initialDemo(release),'dev',id(),time(1));state=simulateDemoRuns(state,'dev',id,time(2));
    const key=suiteReviewKey(state,'dev');
    const rerun=simulateDemoRuns(state,'dev',id,time(3),state.release.release_checks[0].id);
    assert.notEqual(suiteReviewKey(rerun,'dev'),key);
    const edited=saveDemoCheck(state,{...state.release.release_checks[0],script:'# edited'});
    assert.notEqual(suiteReviewKey(edited,'dev'),key);
    const redeployed=registerDemoDeployment(state,'dev',id(),time(4));
    assert.notEqual(suiteReviewKey(redeployed,'dev'),key);
    assert.notEqual(suiteReviewKey(state,'staging'),key);
});
